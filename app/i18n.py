def get_lang(request) -> str:
    lang = request.cookies.get(COOKIE_NAME, DEFAULT_LANG)
    return lang if lang in SUPPORTED else DEFAULT_LANG


def translate(lang: str, key: str, *args, **kwargs) -> str:
    if lang not in SUPPORTED:
        lang = DEFAULT_LANG
    text = MESSAGES[lang].get(key) or MESSAGES[DEFAULT_LANG].get(key, key)
    if args or kwargs:
        try:
            text = text.format(*args, **kwargs)
        except (IndexError, KeyError, ValueError):
            pass
    return text


def tt(request, key: str, *args, **kwargs) -> str:
    """Translate for the language of `request`, with optional .format args."""
    text = translate(get_lang(request), key)
    if args or kwargs:
        try:
            text = text.format(*args, **kwargs)
        except (IndexError, KeyError, ValueError):
            pass
    return text


@pass_context
def jinja_t(context, key: str, *args, **kwargs) -> str:
    """Jinja global: {{ t('key') }} or {{ t('key', n=5) }} — reads lang from context."""
    lang = context.get("lang", DEFAULT_LANG)
    text = translate(lang, key)
